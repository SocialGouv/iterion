// deriveName turns a vendor operation into iterion's `<resource>.<verb>` pair.
//
// The derivation is the package's most consequential piece of taste, because
// the resulting id is what a `.bot` quotes and what must survive a vendor's
// next release. Three rules, in order of how much they can be trusted:
//
//  1. The vendor's first TAG is the resource. It is the grouping the vendor's
//     own documentation uses, it changes rarely, and it is what a human
//     looking for "the issue operations" would search.
//  2. The operationId supplies the verb, with the resource stripped off its
//     front — `issueCreateComment` under tag `issue` reads `create_comment`,
//     not `issue_create_comment`, which would stutter in every call site.
//  3. With no operationId, the METHOD and the path's shape answer: a GET on a
//     collection is `list`, on an item `get`; POST is `create`; PUT/PATCH
//     `update`; DELETE `delete`, each suffixed by the path's last literal
//     segment when that adds meaning.
//
// An overlay pins any id whose derivation would move, which is the escape
// hatch that lets rule 2 stay simple.
func deriveName(tags []string, sourceID, method, path string) (resource, verb string) {
	resource = "api"
	if len(tags) > 0 && strings.TrimSpace(tags[0]) != "" {
		resource = snake(tags[0])
	}
	if sourceID != "" && !isPathEncodedID(sourceID, method) {
		verb = snake(stripResourcePrefix(sourceID, resource))
	}
	if verb == "" {
		verb = deriveVerbFromPath(method, path, resource)
	}
	if verb == "" {
		verb = snake(method)
	}
	return resource, verb
}

// stripResourcePrefix removes the resource from the front of an operationId,
// comparing on the normalised form so `issueCreateComment`, `IssueCreate` and
// `issue_create` all lose the same prefix.
//
// It also strips a vendor's ABBREVIATION of the resource. Naming an operation
// `orgCreateTeam` under tag `organization`, or `repoDeleteKey` under
// `repository`, is a common house style, and an exact-match strip leaves
// `organization.org_create_team` — a stutter in every call site of every
// workflow. Measured on Forgejo: 214 of 506 operations are abbreviated this
// way, against 187 that spell the resource out.
//
// The abbreviation must be a PREFIX of the resource and at least three
// characters, so a coincidence cannot eat a real verb (`get` is not a prefix
// of `group`; `a` would never qualify), and the strip is refused when nothing
// would be left — `userGet` under tag `user` becomes `get`, never "".
func stripResourcePrefix(sourceID, resource string) string {
	normalised := snake(sourceID)
	if normalised == resource {
		return sourceID
	}
	// The WHOLE resource first, which is the only thing that works for a
	// multi-word one: cutting at the first underscore would match `secret`
	// against `secret_scanning` and leave `scanning_bulk_delete_…`, a verb
	// carrying half its own resource.
	if rest, ok := strings.CutPrefix(normalised, resource+"_"); ok && rest != "" {
		return rest
	}
	head, rest, found := strings.Cut(normalised, "_")
	if !found || rest == "" {
		return sourceID
	}
	if len(head) >= 3 && strings.HasPrefix(resource, head) {
		return rest
	}
	return sourceID
}

// isPathEncodedID recognises an operationId a tool generated by concatenating
// the method and the whole path, rather than a name a human chose.
//
// GitLab's description is entirely like this:
// `postApiV4GroupsIdDashEpicsEpicIidIssuesIssueId`, which would become the id
// `gitlab.epics.post_api_v4_groups_id_dash_epics_epic_iid_issues_issue_id` —
// unusable in a `.bot`, and unfixable by hand across 1844 operations. The
// path derivation gives a far better name, so it wins for these.
//
// Two signals must BOTH hold: the id starts with the HTTP method, and it has
// enough segments that no human wrote it. The second is what protects the
// perfectly ordinary `getUser` / `createIssue` style, which starts with a
// method too and whose own name is the better one.
func isPathEncodedID(sourceID, method string) bool {
	n := snake(sourceID)
	if !strings.HasPrefix(n, strings.ToLower(method)+"_") {
		return false
	}
	const pathEncodedSegments = 5
	return strings.Count(n, "_")+1 >= pathEncodedSegments
}

// deriveVerbFromPath is the fallback for a description with no usable
// operation ids. The resource is passed in so the verb does not repeat it:
// `DELETE /groups/{id}/access_requests/{user_id}` under tag `access_requests`
// reads `delete`, not `access_requests.delete_access_requests`.
func deriveVerbFromPath(method, path, resource string) string {
	last := lastLiteralSegment(path)
	if snake(last) == resource {
		last = ""
	}
	endsInParam := strings.HasSuffix(strings.TrimRight(path, "/"), "}")

	var base string
	switch strings.ToLower(method) {
	case "get":
		if endsInParam {
			base = "get"
		} else {
			base = "list"
		}
	case "post":
		base = "create"
	case "put", "patch":
		base = "update"
	case "delete":
		base = "delete"
	default:
		base = strings.ToLower(method)
	}
	if last == "" {
		return base
	}
	return base + "_" + snake(last)
}

// pathScope builds the suffix that tells two same-named operations apart: the
// path's literal segments that the verb and the resource do not already
// carry, minus the API's own prefix noise (`api`, `v4`, `rest`…).
//
// `POST /api/v4/groups/{id}/boards/{board_id}/lists` and its `/projects/`
// twin both derive `boards.create_lists`; this returns `groups` and
// `projects`, so they become `create_lists_groups` and `create_lists_projects`
// — mechanical, readable enough, and stable as long as the endpoint is.
//
// It is capped at two segments: past that a suffix stops disambiguating and
// starts reproducing the path, which is what made GitLab's own operation ids
// unusable in the first place.
func pathScope(path, verb, resource string) string {
	const maxScopeSegments = 2
	var out []string
	for _, seg := range strings.Split(strings.Trim(path, "/"), "/") {
		if seg == "" || strings.HasPrefix(seg, "{") {
			continue
		}
		s := snake(seg)
		if s == "" || isAPIPrefixSegment(s) || s == resource {
			continue
		}
		if strings.Contains("_"+verb+"_", "_"+s+"_") {
			continue // the verb already names it
		}
		out = append(out, s)
		if len(out) == maxScopeSegments {
			break
		}
	}
	return strings.Join(out, "_")
}

// isAPIPrefixSegment recognises the routing noise every REST path starts
// with, which distinguishes nothing between two operations of the same API.
func isAPIPrefixSegment(s string) bool {
	if s == "api" || s == "rest" {
		return true
	}
	// A version segment: `v4`, `v2`, `20` (GitLab's `api/2.0/` normalises to
	// `2_0`, whose head is a digit).
	if len(s) >= 2 && s[0] == 'v' {
		rest := s[1:]
		for _, r := range rest {
			if r < '0' || r > '9' {
				return false
			}
		}
		return true
	}
	return s[0] >= '0' && s[0] <= '9'
}

// lastLiteralSegment returns the last non-templated path segment, which is
// what usually names the sub-resource an operation acts on.
func lastLiteralSegment(path string) string {
	parts := strings.Split(strings.Trim(path, "/"), "/")
	for i := len(parts) - 1; i >= 0; i-- {
		p := parts[i]
		if p == "" || strings.HasPrefix(p, "{") {
			continue
		}
		return p
	}
	return ""
}

// effectFor classifies what an operation does to the remote system.
//
// The METHOD is the baseline, and the VERB corrects it for the one case that
// matters: a POST that searches. Vendors route search through POST whenever
// the query outgrows a URL (Jira's `/search`, Slack's message search), and
// calling those "create" would deny them the retry a read is entitled to —
// the whole reason Effect is a declared field rather than a lookup on the
// method at call time.
// effectFor derives what an operation does to the remote system, from HTTP
// SEMANTICS alone.
//
// The effect decides retry safety: a read may always be repeated, a mutation
// whose answer was lost is `unknown_outcome`. So a wrong "this is a read" is
// not a cosmetic misfiling — it licenses the duplicate the whole class exists
// to prevent.
//
// The derivation used to read the operation's NAME as well, treating a POST
// whose verb began with `get`/`search`/`check`/… as a read. That is unsound
// for the reason every text-matching guard is unsound: the adversary is
// arbitrary text. `getOrCreateLease` snake-cases to `get_or_create_lease`,
// matches the `get_` prefix, and a POST that allocates a lease became an
// operation iterion would blindly retry. Widening the pattern does not
// converge — the next vendor writes `lookupOrProvision`.
//
// So names decide nothing here. A POST is a create, and a genuine POST-search
// (a common shape: GitHub search, GraphQL, Elasticsearch) is stated in the
// overlay's `effect:`, which exists for facts a description cannot express.
// The cost of that is one authored line per such operation; the cost of the
// heuristic was a silent duplicate.
func effectFor(method, _ string) spec.Effect {
	switch strings.ToLower(method) {
	case "get", "head", "options":
		return spec.EffectRead
	case "delete":
		return spec.EffectDelete
	case "put", "patch":
		return spec.EffectUpdate
	case "post":
		return spec.EffectCreate
	}
	// An unrecognised method assumes the MUTATING reading, which is the
	// conservative one: treating an unknown verb as a read would grant it
	// blind retries, and this default is reached exactly when iterion knows
	// least about what the call does.
	return spec.EffectCreate
}

// snake converts camelCase, PascalCase, kebab-case, dotted and spaced names
// into snake_case, collapsing runs of separators and dropping anything that
// is not a letter or a digit. It is what makes an id safe to quote in a
// `.bot`, in a URL segment and in an MCP tool name at once.
func snake(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 4)
	prevLower := false
	prevDigit := false
	for _, r := range s {
		switch {
		case r >= 'A' && r <= 'Z':
			// A boundary before an upper-case run that follows a lower-case
			// letter or a digit: "createComment" → create_comment, and
			// "v2Token" → v2_token.
			if prevLower || prevDigit {
				b.WriteByte('_')
			}
			b.WriteRune(r - 'A' + 'a')
			prevLower = false
			prevDigit = false
		case (r >= 'a' && r <= 'z'):
			b.WriteRune(r)
			prevLower = true
			prevDigit = false
		case r >= '0' && r <= '9':
			b.WriteRune(r)
			prevLower = false
			prevDigit = true
		default:
			// Any separator (space, '-', '.', '/', '_') collapses to one '_'.
			if b.Len() > 0 && !strings.HasSuffix(b.String(), "_") {
				b.WriteByte('_')
			}
			prevLower = false
			prevDigit = false
		}
	}
	return strings.Trim(b.String(), "_")
}
