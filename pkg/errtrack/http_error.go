package errtrack

import (
	"bufio"
	"net"
	"net/http"
	"os"

	sentry "github.com/getsentry/sentry-go"
	"github.com/google/uuid"

	"github.com/SocialGouv/iterion/pkg/log"
)

// HTTPErrorWriter binds the request and its logger to the response writer so
// helpers without a request argument can report a failure at the same boundary.
// Unwrap keeps ResponseController operations available through the wrapper.
func HTTPErrorWriter(w http.ResponseWriter, r *http.Request, logger *log.Logger) http.ResponseWriter {
	return &httpErrorWriter{ResponseWriter: w, request: r, logger: logger}
}

type httpErrorWriter struct {
	http.ResponseWriter
	request *http.Request
	logger  *log.Logger
}

func (w *httpErrorWriter) Unwrap() http.ResponseWriter { return w.ResponseWriter }

// Flush and Hijack retain the interfaces used by SSE and WebSocket handlers.
func (w *httpErrorWriter) Flush() { _ = http.NewResponseController(w.ResponseWriter).Flush() }

func (w *httpErrorWriter) Hijack() (net.Conn, *bufio.ReadWriter, error) {
	return http.NewResponseController(w.ResponseWriter).Hijack()
}

func (w *httpErrorWriter) Push(target string, opts *http.PushOptions) error {
	if p, ok := w.ResponseWriter.(http.Pusher); ok {
		return p.Push(target, opts)
	}
	return http.ErrNotSupported
}

// HTTPErrorMiddleware supplies request context even when tracing is disabled.
// Install it inside HTTPMiddleware so a traced request carries its span.
func HTTPErrorMiddleware(logger *log.Logger) func(http.Handler) http.Handler {
	return func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			next.ServeHTTP(HTTPErrorWriter(w, r, logger), r)
		})
	}
}

var fallbackHTTPLogger = log.New(log.LevelError, os.Stderr)

// HTTPFailure logs the internal cause and returns only opaque correlation IDs.
// The caller writes its generic public body. An inbound request ID is never
// trusted: each failure receives an ID generated by the server.
func HTTPFailure(w http.ResponseWriter, status int, cause string) map[string]string {
	ids := map[string]string{"request_id": uuid.NewString()}
	logger := fallbackHTTPLogger
	fields := map[string]any{"request_id": ids["request_id"], "http_status": status}
	for current := w; current != nil; {
		if bound, ok := current.(*httpErrorWriter); ok {
			if bound.logger != nil {
				logger = bound.logger
			}
			if r := bound.request; r != nil {
				fields["http_method"] = r.Method
				fields["http_path"] = r.URL.Path
				if span := sentry.SpanFromContext(r.Context()); span != nil {
					ids["trace_id"] = span.TraceID.String()
					fields["trace_id"] = ids["trace_id"]
				}
			}
			break
		}
		unwrapper, ok := current.(interface{ Unwrap() http.ResponseWriter })
		if !ok {
			break
		}
		current = unwrapper.Unwrap()
	}
	if logger == fallbackHTTPLogger {
		AttachLogHook(logger)
	}
	w.Header().Set("X-Request-ID", ids["request_id"])
	logger.WithFields(fields).Error("http: request failed (request_id=%s trace_id=%s status=%d method=%v path=%v): %s", ids["request_id"], ids["trace_id"], status, fields["http_method"], fields["http_path"], cause)
	return ids
}
