// catalogTemplateRoot and exampleCatalogTemplateRoot are the two roots of
// the snapshot/restore set — every catalog template
// RegenerateWhatsNextCatalog's own write set can reach. The recursive walk
// this replaced SkipDir'd a missing examples/, leaving the guard green over
// a write set it no longer mirrored; catalogRootFiles floors the bots/ root
// on its own. No example ships a template today, so the examples root
// carries floor 0: a template added there must join the snapshot set, and
// its presence is what the root tracks. A template nested one level deeper
// than today's flat layout reddens the routing guard before it can reach
// regen's write set unseen.
var (
	catalogTemplateRoot        = catalogRoot{"*/iterion-bot-catalog-static.md", 2, "every router bundle's generated-catalog template"}
	exampleCatalogTemplateRoot = catalogRoot{"../examples/*/iterion-bot-catalog-static.md", 0, "catalog templates under examples/ — none ships today; a new one joins the snapshot set"}
)

func catalogTemplates(t *testing.T) []string {
	return append(catalogRootFiles(t, catalogTemplateRoot), catalogRootFiles(t, exampleCatalogTemplateRoot)...)
}

// TestCommittedCatalogIsFresh fails when the committed generated catalog
// (bots/whats-next/skills/iterion-bot-catalog.md) no longer matches what the
// current manifests render. A stale committed catalog is not cosmetic: the
// run of the bot that OWNS it refreshes that copy at start, so when its
// bundle is the one inside the run's workspace (Nexie is `worktree: none`)
// the regen produces a real diff against HEAD and the finalize wip-banks an
// otherwise-clean run (observed on back-to-back smoke runs, 2026-07-07).
// When this fails, run `iterion bots regen-catalog` and commit the result
// alongside the manifest change.
func TestCommittedCatalogIsFresh(t *testing.T) {
	repoRoot, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	// Every bundle shipping the static template owns a generated catalog
	// (whats-next, issue-triage, …) — snapshot each committed copy, regen
	// all of them, and compare in place. The snapshot set is the corpus's
	// template roots (catalogTemplateRoot, floored at two — both router
	// bundles ship one), so a template the snapshot misses reddens there
	// instead of being rewritten by regen without ever being snapshotted
	// or restored.
	templates := catalogTemplates(t)
	committed := map[string][]byte{}
	for _, tmpl := range templates {
		genPath := filepath.Join(filepath.Dir(tmpl), "skills", "iterion-bot-catalog.md")
		b, err := os.ReadFile(genPath)
		if err != nil {
			t.Fatalf("read committed catalog %s: %v", genPath, err)
		}
		committed[genPath] = b
	}

	// RegenerateWhatsNextCatalog writes atomically to each SOURCE path —
	// per-bundle, INSIDE its loop — so even a mid-loop regen FAILURE (a
	// malformed template, a write error) leaves earlier bundles'
	// catalogs rewritten. The guard therefore snapshots, regenerates,
	// reads the regenerated bytes, and only then restores EVERY committed
	// copy unconditionally — the tree is returned to its pre-test state on
	// every exit path — before reporting (a deterministic, sorted list).
	_, regenErr := botregistry.RegenerateWhatsNextCatalog(context.Background(), repoRoot)
	regenerated := map[string][]byte{}
	for genPath := range committed {
		b, err := os.ReadFile(genPath)
		if err != nil {
			t.Fatalf("read regenerated catalog %s: %v", genPath, err)
		}
		regenerated[genPath] = b
	}
	var stale, restoreFailed []string
	for genPath, before := range committed {
		if writeErr := os.WriteFile(genPath, before, 0o644); writeErr != nil {
			// A restore that cannot happen re-opens the silent-dirty-tree
			// class this guard exists to kill — loud, never a Logf.
			restoreFailed = append(restoreFailed, fmt.Sprintf("%s: %v", genPath, writeErr))
		}
		if regenErr == nil && string(regenerated[genPath]) != string(before) {
			stale = append(stale, genPath)
		}
	}
	if len(restoreFailed) > 0 {
		sort.Strings(restoreFailed)
		t.Fatalf("could not restore the committed catalogs after regenerating: %s — the working tree may hold regenerated content; restore with `git checkout -- <paths>`", strings.Join(restoreFailed, ", "))
	}
	if regenErr != nil {
		t.Fatalf("regenerate: %v", regenErr)
	}
	if len(stale) > 0 {
		sort.Strings(stale)
		t.Fatalf("committed catalog(s) STALE vs the current manifests: %s.\n"+
			"Every run-start regen will dirty the worktree (and wip-bank clean runs).\n"+
			"Fix: run `iterion bots regen-catalog` and commit the listed file(s) with your manifest change.",
			strings.Join(stale, ", "))
	}
}
